def _keyword_classify(text: str) -> str:
    text_lower = text.lower()
    scores = {cat: 0 for cat in VALID_CATEGORIES}

    for category, keywords in KEYWORD_MAP.items():
        for kw in keywords:
            if kw in text_lower:
                scores[category] += 1

    best_category = max(scores, key=scores.__getitem__)
    best_score = scores[best_category]

    logger.info(f"Keyword-классификация: выбрана={best_category!r} (совпадений: {best_score})")

    if best_score == 0:
        return "логические рассуждения"  # дефолтная категория

    return best_category


def classify_task(user_message: str) -> str:
    prompt = (
        "Определи категорию задачи. Ответь ТОЛЬКО одним словом или фразой из списка:\n"
        "программирование, математика, логика, текст, перевод, документы, данные, "
        "мультимодальные, скорость, стоимость.\n\n"
        f"Задача: \"{user_message}\"\n\n"
        "Категория:"
    )

    try:
        response = analyze_task(prompt).strip().lower()
        logger.info(f"Ответ Ollama: {response!r}")

        # Проверяем точное совпадение с категориями
        for cat in VALID_CATEGORIES:
            if cat in response:
                logger.info(f"Ollama: точное совпадение с '{cat}'")
                return cat

        # Проверяем псевдонимы
        for alias, full_cat in CATEGORY_ALIASES.items():
            if alias in response:
                logger.info(f"Ollama: псевдоним '{alias}' → '{full_cat}'")
                return full_cat

        logger.warning(f"Ollama не вернул валидную категорию ({response!r}), keyword fallback")
        return _keyword_classify(user_message)

    except Exception as e:
        logger.warning(f"Ollama недоступен ({e}), keyword fallback")
        return _keyword_classify(user_message)